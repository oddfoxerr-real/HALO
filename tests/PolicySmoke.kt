package dev.oddfoxerr.halo

/** Runnable without Android SDK: kotlinc Profiles.kt PolicySmoke.kt -include-runtime -d test.jar */
fun main() {
    check(CharacterApp.fromPackage("com.discord") == CharacterApp.DISCORD)
    check(CharacterApp.fromPackage("com.whatsapp.w4b") == CharacterApp.WHATSAPP)
    check(CharacterApp.fromPackage("com.google.android.youtube") == CharacterApp.YOUTUBE)
    check(CharacterApp.fromPackage("com.google.android.gm") == CharacterApp.GMAIL)
    check(CharacterApp.fromPackage("com.some.other.app") == CharacterApp.OTHER)
    val tracker = NotificationTracker()
    check(tracker.posted("key1", "com.discord") == CharacterApp.DISCORD)
    check(tracker.posted("key1", "com.discord") == null) // update must not replay
    check(tracker.posted("key2", "com.whatsapp") == CharacterApp.WHATSAPP)
    check(tracker.countFor(CharacterApp.DISCORD) == 1)
    check(tracker.mostRecent() == CharacterApp.WHATSAPP)
    check(tracker.removed("key2"))
    check(tracker.mostRecent() == CharacterApp.DISCORD)
    check(!tracker.removed("key2"))
    tracker.restore(listOf("third" to "com.google.android.youtube"))
    check(tracker.size() == 1 && tracker.mostRecent() == CharacterApp.YOUTUBE)
    tracker.clear()
    check(tracker.size() == 0)
    val profiles = CharacterApp.entries.map(::CharacterProfile)
    check(profiles.size == 5)
    check(profiles.all { it.anchorY == .50f && it.edgeInsetDp == 0f })
    check(profiles.all { it.enabled && it.persistent })
    check(profiles.map { it.color }.distinct().size == 5)
    val original = CharacterProfile(CharacterApp.DISCORD)
    val tuned = original.copy(scale = 1.55f, anchorY = .78f, edgeInsetDp = 18f)
    check(original.scale == 1f && original.anchorY == .50f)
    check(tuned.scale == 1.55f && tuned.anchorY == .78f && tuned.edgeInsetDp == 18f)
    check(QuietHoursPolicy.isQuiet(true, 1320, 420, 1380))
    check(QuietHoursPolicy.isQuiet(true, 1320, 420, 360))
    check(!QuietHoursPolicy.isQuiet(true, 1320, 420, 720))
    check(!QuietHoursPolicy.isQuiet(false, 1320, 420, 1380))
    check(QuietHoursPolicy.isQuiet(true, 480, 1020, 600))
    check(!QuietHoursPolicy.isQuiet(true, 480, 1020, 1100))
    check(QuietHoursPolicy.isQuiet(true, 480, 480, 200))
    val rule = ApplicationRule("com.discord", CharacterApp.OTHER, false, 0xFFBAA5E7L)
    check(rule.character == CharacterApp.OTHER)
    check(!rule.enabled && rule.colorOverride == 0xFFBAA5E7L)
    check(tracker.newestPackages().isEmpty())
    tracker.posted("appkey", "org.custom.app")
    check(tracker.newestPackages() == listOf("org.custom.app"))
    check(NotificationEligibilityPolicy.isAlerting(false, null))
    check(NotificationEligibilityPolicy.isAlerting(false, 3))
    check(NotificationEligibilityPolicy.isAlerting(false, 5))
    check(!NotificationEligibilityPolicy.isAlerting(false, 2))
    check(!NotificationEligibilityPolicy.isAlerting(false, 1))
    check(NotificationEligibilityPolicy.isAlerting(true, 1))
    val silent = NotificationTracker()
    check(silent.posted("silent-key", "com.discord", false) == CharacterApp.DISCORD)
    check(silent.newestIndicatorPackages().isEmpty())
    check(silent.posted("alerting-key", "com.whatsapp", true) == CharacterApp.WHATSAPP)
    check(silent.newestIndicatorPackages() == listOf("com.whatsapp"))
    check(silent.posted("silent-key", "com.discord", true) == null)
    check(silent.newestIndicatorPackages() == listOf("com.whatsapp", "com.discord"))
    silent.restoreEligible(listOf(Triple("x", "com.google.android.gm", false), Triple("y", "com.discord", true)))
    check(silent.newestIndicatorPackages() == listOf("com.discord"))
    println("HALO policy smoke checks passed (44 assertions).")
}
